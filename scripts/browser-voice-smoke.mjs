import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel:'chromium', headless:true, args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page = await browser.newPage({viewport:{width:1440,height:1080}});
const errors=[];
page.on('pageerror', e => errors.push(e.message));
try {
  await page.addInitScript(() => {
    window.previewSamples = 0;
    const original = AudioContext.prototype.createBuffer;
    AudioContext.prototype.createBuffer = function(channels, length, rate) { window.previewSamples += length; return original.call(this, channels, length, rate); };
  });
  await page.goto('http://127.0.0.1:5174');
  await page.getByText('数字人已就绪', {exact:false}).waitFor({timeout:60000});
  if(process.env.DEMO_API_ACCESS_KEY) await page.locator('input[type=password]').fill(process.env.DEMO_API_ACCESS_KEY);
  const catalog=await (await page.request.get('http://127.0.0.1:8090/api/tts/voices')).json();
  assert.ok(catalog.enabled && catalog.voices.length);
  const selectedVoice=catalog.default_voice ?? catalog.voices[0].id;
  const picker=page.getByLabel('语音音色');
  await picker.waitFor();
  assert.equal(await picker.locator('option').count(),catalog.voices.length);
  assert.equal(await picker.locator('optgroup').count(),new Set(catalog.voices.map(v=>v.language)).size);
  await picker.selectOption(selectedVoice);
  assert.ok((await page.locator('.voice-picker p').innerText()).includes(catalog.provider_label));
  const preview = page.waitForResponse(r => r.url().endsWith('/api/tts/preview'));
  await page.getByRole('button',{name:'试听',exact:true}).click();
  const response=await preview;
  assert.equal(response.status(),200);
  assert.equal(response.request().postDataJSON().voice,selectedVoice);
  await page.waitForFunction(() => window.previewSamples > 2400, null, {timeout:60000});
  await page.getByRole('button',{name:'试听',exact:true}).waitFor({timeout:60000});
  const token = page.waitForRequest(r => r.url().endsWith('/api/token'));
  await page.getByRole('button',{name:/开始对话/}).click();
  assert.equal((await token).postDataJSON().tts_voice,selectedVoice);
  await page.getByText('正在聆听',{exact:true}).waitFor({timeout:90000});
  assert.equal(await picker.isDisabled(),true);
  await page.getByRole('textbox',{name:'消息'}).fill('请只回答：你好。');
  await page.getByRole('button',{name:'发送',exact:true}).click();
  await page.waitForFunction(() => document.querySelectorAll('.message.agent').length >= 2, null, {timeout:90000});
  assert.ok(await page.locator('.message-time').count() >= 2);
  await page.screenshot({path:'docs/demo-kokoro.png',fullPage:true});
  await page.getByRole('button',{name:/结束对话/}).click();
  await page.waitForFunction(() => !document.querySelector('#tts-voice').disabled);
  await page.reload();
  await picker.waitFor();
  assert.equal(await picker.inputValue(),selectedVoice);
  assert.deepEqual(errors,[]);
  console.log('PASS: provider voice catalog, language groups, streamed PCM preview, selected voice in token request, real agent reply, timestamps, session locking, persistence; no page errors');
} catch (error) { await page.screenshot({path:'docs/demo-kokoro-failure.png',fullPage:true}); throw error; } finally { await browser.close(); }
